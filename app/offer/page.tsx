type Block =
  | { kind: "title" | "section"; text: string }
  | { kind: "paragraph"; text: string[] }
  | { kind: "list"; items: string[] };

function createBlocks(): Block[] {
  const blocks: Block[] = [];
  let paragraph: string[] = [];
  let list: string[] = [];

  const flushParagraph = () => {
    if (paragraph.length > 0) {
      blocks.push({ kind: "paragraph", text: paragraph });
      paragraph = [];
    }
  };

  const flushList = () => {
    if (list.length > 0) {
      blocks.push({ kind: "list", items: list });
      list = [];
    }
  };

  for (const line of offerText.split("\n")) {
    if (line.trim() === "") {
      flushParagraph();
      flushList();
      continue;
    }

    if (line.startsWith("# ")) {
      flushParagraph();
      flushList();
      blocks.push({
        kind: line.startsWith("# ДОГОВОР") ? "title" : "section",
        text: line.slice(2),
      });
      continue;
    }

    if (line.startsWith("## ")) {
      flushParagraph();
      flushList();
      blocks.push({ kind: "section", text: line.slice(3) });
      continue;
    }

    if (line.startsWith("- ")) {
      flushParagraph();
      list.push(line.slice(2));
      continue;
    }

    flushList();
    paragraph.push(line);
  }

  flushParagraph();
  flushList();
  return blocks;
}

function createSections(): Block[][] {
  const sections: Block[][] = [];
  let currentSection: Block[] = [];

  for (const block of createBlocks()) {
    if (block.kind === "section" && currentSection.length > 0) {
      sections.push(currentSection);
      currentSection = [];
    }

    currentSection.push(block);
  }

  if (currentSection.length > 0) {
    sections.push(currentSection);
  }

  return sections;
}

function renderInline(text: string): ReactNode[] {
  const tokens = text.split(/(\*\*[^*]+\*\*|\[[^\]]+\]\(mailto:[^)]+\))/g);

  return tokens.filter(Boolean).map((token, index) => {
    if (token.startsWith("**") && token.endsWith("**")) {
      return (
        <strong key={index} className={emphasisClass}>
          {renderInline(token.slice(2, -2))}
        </strong>
      );
    }

    const linkMatch = token.match(/^\[([^\]]+)\]\(mailto:([^)]+)\)$/);
    if (linkMatch) {
      return (
        <a key={index} className={emailClass} href={`mailto:${linkMatch[2]}`}>
          {linkMatch[1]}
        </a>
      );
    }

    return <span key={index}>{token}</span>;
  });
}

